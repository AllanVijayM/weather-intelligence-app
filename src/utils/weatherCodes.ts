export function getWeatherCodeInfo(code: number): WeatherCodeInfo {
  if (WEATHER_CODES[code]) {
    return WEATHER_CODES[code];
  }
  
  // Fallback map for unlisted codes
  if (code >= 1 && code <= 3) return WEATHER_CODES[2];
  if (code >= 51 && code <= 57) return WEATHER_CODES[53];
  if (code >= 61 && code <= 67) return WEATHER_CODES[63];
  if (code >= 71 && code <= 77) return WEATHER_CODES[73];
  if (code >= 80 && code <= 82) return WEATHER_CODES[81];
  if (code >= 85 && code <= 86) return WEATHER_CODES[85];
  if (code >= 95 && code <= 99) return WEATHER_CODES[95];

  return WEATHER_CODES[0];
}
